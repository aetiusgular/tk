#!/usr/bin/env node
// Generates src/core/confusables.ts from Unicode's confusables.txt (UTS #39).
//
//   node packages/tk-claude-plugin/scripts/gen-confusables.mjs <path to confusables.txt>
//
// Keeps only mappings whose source is one non-ASCII code point and whose
// target is one or more printable ASCII characters (U+0021 to U+007E), as
// lane A does. That is the "Latin targets only" reading of
// contracts/policy.md section 3: the reject list's keys are ASCII, so only
// look-alikes of ASCII matter.
// ASCII sources (for example "0" mapped to "O") are left out, because
// folding ASCII into other ASCII would change ordinary text.
//
// Pinned input: unicode-org/unicodetools at 578f6c0, file
// unicodetools/data/security/17.0.0/confusables.txt, header "Version: 17.0.0",
// "Date: 2025-07-22", sha256 091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a.
// The script refuses any other file.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PINNED_SHA256 = "091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a";

const input = process.argv[2];
if (!input) {
  console.error("usage: gen-confusables.mjs <confusables.txt>");
  process.exit(2);
}
const raw = readFileSync(input);
const sha = createHash("sha256").update(raw).digest("hex");
if (sha !== PINNED_SHA256) {
  console.error(`confusables.txt sha256 ${sha} is not the pinned ${PINNED_SHA256}`);
  process.exit(1);
}

const pairs = [];
for (const line of raw.toString("utf8").split("\n")) {
  const body = line.split("#")[0].trim();
  if (!body) continue;
  const [src, dst] = body.split(";").map((s) => s.trim());
  if (!src || !dst) continue;
  const srcCps = src.split(/\s+/);
  const dstCps = dst.split(/\s+/);
  if (srcCps.length !== 1) continue;
  const s = Number.parseInt(srcCps[0], 16);
  const d = dstCps.map((x) => Number.parseInt(x, 16));
  if (s < 0x80) continue;
  if (d.some((c) => c < 0x21 || c > 0x7e)) continue;
  pairs.push([s, d]);
}
pairs.sort((a, b) => a[0] - b[0]);

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "src", "core", "confusables.ts");
const encoded = pairs.map(([s, d]) => `${s.toString(36)}:${d.map((c) => c.toString(36)).join(".")}`).join(",");
const text = `// GENERATED by scripts/gen-confusables.mjs. Do not edit by hand.
// Source: Unicode confusables.txt 17.0.0 (2025-07-22), sha256 ${PINNED_SHA256},
// from unicode-org/unicodetools at 578f6c0. ${pairs.length} mappings from one non-ASCII
// code point to printable ASCII. Each entry is "<source>:<target>[.<target>...]",
// code points in base 36, entries joined by ",".

const ENCODED =
  "${encoded}";

/** Code point to its ASCII look-alike. */
export const CONFUSABLES: ReadonlyMap<number, string> = (() => {
  const map = new Map<number, string>();
  for (const entry of ENCODED.split(",")) {
    const [source, target] = entry.split(":");
    map.set(Number.parseInt(source ?? "", 36), (target ?? "").split(".").map((t) => String.fromCharCode(Number.parseInt(t, 36))).join(""));
  }
  return map;
})();

export const CONFUSABLES_COUNT = ${pairs.length};
`;
writeFileSync(out, text);
console.log(`wrote ${pairs.length} mappings to ${out}`);
