#!/usr/bin/env node
// Generates src/confusables.ts from a pinned copy of Unicode TR39
// confusables.txt (contracts/policy.md, section 3, "Folding").
//
// Usage: node packages/tk-pi/scripts/gen-confusables.mjs <path/to/confusables.txt>
//
// Pinned input: Unicode 17.0.0, fetched from
//   https://raw.githubusercontent.com/unicode-org/unicodetools/578f6c0516f5f268292ebda50b51848407a06478/unicodetools/data/security/17.0.0/confusables.txt
// sha256 091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a
// (the file says "Version: 17.0.0", "Date: 2025-07-22"). Any other file is
// refused, so the table cannot drift without this script changing.
//
// Kept: single-code-point sources above U+007F whose target is made only of
// printable ASCII (U+0021 to U+007E): "Latin targets only", plus the ASCII
// punctuation the reject keys use (`_`, `-`, `.`, `:`, `/`). ASCII sources
// are never mapped, so ASCII text folds to itself apart from lowercasing.
// Network: none. The file is read from the path given.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PINNED_SHA256 = "091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a";
const VERSION = "17.0.0";

const input = process.argv[2];
if (!input || process.argv.length !== 3) {
  console.error("usage: gen-confusables.mjs <confusables.txt>");
  process.exit(2);
}
const bytes = readFileSync(input);
const sha = createHash("sha256").update(bytes).digest("hex");
if (sha !== PINNED_SHA256) {
  console.error(`refused: sha256 ${sha} is not the pinned ${PINNED_SHA256}`);
  process.exit(1);
}

const entries = [];
for (const raw of bytes.toString("utf8").split("\n")) {
  const line = raw.split("#")[0].trim();
  if (!line) continue;
  const parts = line.split(";").map((p) => p.trim());
  if (parts.length < 3) continue;
  const src = parts[0].split(/\s+/);
  if (src.length !== 1) continue;
  const s = Number.parseInt(src[0], 16);
  if (!(s > 0x7f)) continue;
  const tgt = parts[1].split(/\s+/).map((h) => Number.parseInt(h, 16));
  if (!tgt.every((t) => t >= 0x21 && t <= 0x7e)) continue;
  entries.push([s, String.fromCodePoint(...tgt)]);
}
entries.sort((a, b) => a[0] - b[0]);

const body = entries.map(([s, t]) => `${s.toString(16)}\t${t}`).join("\n");
const out = `// GENERATED by scripts/gen-confusables.mjs. Do not edit by hand.
// Unicode TR39 confusables.txt ${VERSION}, sha256 ${PINNED_SHA256}.
// ${entries.length} entries: a non-ASCII code point (hex) and its printable-ASCII
// look-alike, one per line, tab-separated.
// Data: Copyright (c) 2025 Unicode, Inc. Unicode License V3,
// https://www.unicode.org/license.txt

export const CONFUSABLES_VERSION = ${JSON.stringify(VERSION)};
export const CONFUSABLES_SHA256 = ${JSON.stringify(PINNED_SHA256)};
export const CONFUSABLES_COUNT = ${entries.length};

export const CONFUSABLES_TABLE = ${JSON.stringify(body)};
`;
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "confusables.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${entries.length} entries`);
